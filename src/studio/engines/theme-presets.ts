export function duplicateThemePreset(
  source: Pick<CustomThemePreset, 'name' | 'description' | 'theme'>,
  customName?: string
): CustomThemePreset {
  const nextName = (customName && customName.trim()) || `${source.name} (Copy)`;
  return {
    id: `custom_theme_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 6)}`,
    name: nextName,
    description: source.description || 'Custom duplicated theme preset',
    theme: JSON.parse(JSON.stringify(source.theme)) as FormTheme,
    isCustom: true,
    createdAt: new Date().toISOString(),
  };
}
